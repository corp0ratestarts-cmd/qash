// Schema emitter / parity checker for genesis constants.
//
// Usage:
//   cargo run --bin generate-schema              — emit schema to stdout
//   cargo run --bin generate-schema -- --check   — verify spec/genesis.schema.toml
//                                                   matches GENESIS_CONSTANTS.toml;
//                                                   exits non-zero on any mismatch.
//
// Domain B tool — not on the consensus path.

use std::collections::BTreeMap;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let check_mode = args.iter().any(|a| a == "--check");

    if check_mode {
        run_check();
    } else {
        emit_schema();
    }
}

// Pinned genesis values (must be kept in sync with lyapunov.rs / GENESIS_CONSTANTS.toml).
// These are the same values asserted by params.rs const guards.
struct GenesisSchema {
    version:                  &'static str,
    lock_algorithm:           &'static str,
    scale:                    i128,
    intermediate_width:       u32,
    overflow_policy:          &'static str,
    weight_divergence_d:      i128,
    weight_conflict_c:        i128,
    weight_slash_sigma:       i128,
    weight_cascade_health_ch: i128,
    epsilon_threshold:        i128,
    max_queries_per_epoch:    i128,
    cascade_depth:            u32,
    cascade_composition_mode: &'static str,
    binding_primitive:        &'static str,
    epoch_duration_ms:        u32,
    max_control_loop_ms:      u32,
    leaf_index_bytes:         u32,
    sparse_merkle_depth:      u32,
}

